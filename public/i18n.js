function detectLang() {
  let saved = null;
  try { saved = JSON.parse(localStorage.getItem('sincro.lang')); } catch {}
  if (saved && DICT[saved]) return saved;
  return /^es/i.test(navigator.language || '') ? 'es' : 'en';
}
let LANG = detectLang();

function t(key, params) {
  let s = (DICT[LANG] && DICT[LANG][key]) || DICT.es[key] || key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split('{' + k + '}').join(v);
  return s;
}

/** Aplica el idioma a los textos fijos del HTML (data-i18n, data-i18n-html, data-i18n-placeholder, data-i18n-title). */
function applyStaticI18n() {
  document.documentElement.lang = LANG;
  document.title = t('app.title');
  document.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((n) => { n.placeholder = t(n.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-i18n-title]').forEach((n) => { n.title = t(n.dataset.i18nTitle); });
  document.querySelectorAll('.lang-sel').forEach((s) => { s.value = LANG; });
}
